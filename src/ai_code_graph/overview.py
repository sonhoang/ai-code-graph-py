"""Render ``overview.md``: a table of contents of the codebase, grouped by package.

It lists each module's exported symbols as one signature line each, so a model
(or a new teammate) can see the shape of the code without opening files.
"""

from __future__ import annotations

from collections import defaultdict

from . import __version__
from .model import Graph, Module, Symbol

DOC_WIDTH = 80


def render_overview(graph: Graph, prefix: str | None = None) -> str:
    """Markdown overview; ``prefix`` keeps only modules whose dotted name starts with it."""
    modules = [m for m in graph.modules.values() if prefix is None or _in_namespace(m.name, prefix)]
    n_symbols = sum(len(m.symbols) for m in modules)
    lines = [
        "# Code map",
        "",
        f"{len(modules)} modules, {n_symbols} symbols. "
        f"Generated by ai-code-graph-py {__version__}; regenerate with `ai-code-graph sync`.",
        "Each entry is `L<line> <signature>`; public methods are listed under their class.",
    ]

    groups: dict[str, list[Module]] = defaultdict(list)
    for m in modules:
        groups[m.name if m.is_package else m.package].append(m)

    for package in sorted(groups, key=lambda p: (p == "", p)):  # loose scripts go last
        lines += ["", f"## {package or '(top-level modules)'}"]
        for m in sorted(groups[package], key=lambda m: (not m.is_package, m.name)):
            lines += ["", *_module_section(graph, m)]

    broken = sorted(m.path for m in modules if m.error)
    if broken:
        lines += ["", "## Files that failed to parse", ""]
        lines += [f"- `{p}`: {graph.modules[p].error}" for p in broken]
    return "\n".join(lines) + "\n"


def _module_section(graph: Graph, m: Module) -> list[str]:
    out = [f"### {m.name} (`{m.path}`)"]
    if m.doc:
        out.append(_clip(m.doc))
    for sym in m.exported():
        out.append(f"- {_entry(sym)}")
        if sym.kind == "class":
            methods = [
                s.name
                for s in m.symbols
                if s.qualname.startswith(sym.qualname + ".")
                and s.kind == "method"
                and s.is_public
                and s.qualname.count(".") == sym.qualname.count(".") + 1
            ]
            if methods:
                out.append(f"  - methods: {', '.join(methods)}")
    if m.all is not None:
        defined = {s.name for s in m.symbols}
        reexported = [name for name in m.all if name not in defined]
        if reexported:
            out.append(f"- re-exports: {', '.join(reexported)}")
    local = sorted({graph.modules[p].name for imp in m.imports for p in imp.resolved} - {m.name})
    if local:
        out.append(f"- imports: {', '.join(local)}")
    if m.imported_by:
        importers = sorted(graph.modules[p].name for p in m.imported_by)
        out.append(f"- imported by: {', '.join(importers)}")
    return out


def _entry(sym: Symbol) -> str:
    doc = f" - {_clip(sym.doc)}" if sym.doc else ""
    return f"L{sym.line} `{sym.head()}`{doc}"


def _in_namespace(name: str, prefix: str) -> bool:
    return name == prefix or name.startswith(prefix + ".")


def _clip(text: str) -> str:
    return text if len(text) <= DOC_WIDTH else text[: DOC_WIDTH - 3] + "..."
